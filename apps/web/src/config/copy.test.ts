/**
 * The thirteenth round's copy (FRONTEND.md §4.3): placeholders and links well formed, the How it
 * works page's numbers all filled from the config, its links pointing at the app's pages or its own
 * anchors, the two Claim labels, and every string in FRONTEND.md §4.3 word for word. The 143 strings
 * were approved as written by the owner on 2026-10-11 (thirteenth round), the 7 mobile-wallet
 * strings as drafted on 2026-10-13 (O-6 lifted), and pump's 2 v3 error texts as drafted on
 * 2026-10-13 (pump-final D4): a string that changes, or one added, fails here until §4.3 —
 * regenerated by `scripts/owner-copy.ts --doc` — carries it, and the count pins the approved set
 * (152).
 */
import { describe, expect, it } from 'vitest';
import { BEGIN, docBlock, END, MOBILE_APPROVAL, PUMP_APPROVAL } from '../../scripts/owner-copy.ts';
import { guideVars } from '../features/guide/HowItWorksPage.tsx';
import { fullGlobalConfig } from '../features/markets/test/fixtures.ts';
import { readRepo } from '../test/repo.ts';
import { COPY, type CopyId, copy, copyParts, copyPlaceholders, HOW_IT_WORKS } from './copy.ts';
import { PUMP_COPY } from './copyPump.ts';
import { WALLET_COPY, walletCopy } from './copyWallet.ts';
import { percent } from './disclosureVars.ts';
import { programError } from './errors.ts';
import { GLOSSARY, GLOSSARY_UI } from './glossary.ts';

const ids = Object.keys(COPY) as CopyId[];

describe('copy', () => {
    it('gives every string its text, where it shows and its sources', () => {
        for (const id of ids) {
            expect(COPY[id].text.length, id).toBeGreaterThan(0);
            expect(COPY[id].where.length, id).toBeGreaterThan(0);
            expect(COPY[id].sources.length, id).toBeGreaterThan(0);
        }
    });

    it('fills placeholders and refuses to render a missing one', () => {
        expect(copyPlaceholders('claim.label.syncs')).toEqual(['c', 'g']);
        expect(copy('claim.label.syncs', { c: '0', g: '0.000025' })).toBe(
            'Review claim · 0 SOL now · syncs may add up to 0.000025 SOL',
        );
        expect(copy('claim.label.full', { c: '0.5' })).toBe('Review claim · 0.5 SOL');
        expect(() => copy('claim.label.syncs', { c: '0' })).toThrow(/missing \{g\}/);
    });

    it('has every How it works number from the live config (no word stands in for one)', () => {
        const vars = guideVars(fullGlobalConfig());
        const pageIds = HOW_IT_WORKS.flatMap((b) =>
            b.kind === 'list' ? b.ids : b.kind === 'disclosure' ? [] : [b.id],
        );
        for (const id of pageIds) {
            for (const p of copyPlaceholders(id)) expect(vars[p], `${id}: {${p}}`).toBeDefined();
            expect(copy(id, vars), id).not.toMatch(/\{\w+\}/);
        }
        expect(vars.exTier).toBe('C');
        expect(vars.durMin).toBe('3 days');
        expect(vars.durMax).toBe('30 days');
        expect(vars.openFee).toBe('0.1%');
        // The penalty split is a share of the penalty (SPEC §6.3: 50 / 20 / 30).
        expect([vars.penLender, vars.penProtocol, vars.penKeeper]).toEqual(['60%', '10%', '30%']);
        expect([percent(5_000), percent(250), percent(10), percent(1_000), percent(0)]).toEqual([
            '50%',
            '2.5%',
            '0.1%',
            '10%',
            '0%',
        ]);
    });

    it('links only to the app’s static pages or to anchors on the page', () => {
        const anchors = new Set(HOW_IT_WORKS.flatMap((b) => ('anchor' in b && b.anchor ? [b.anchor] : [])));
        for (const id of ids) {
            for (const part of copyParts(id)) {
                if (part.kind !== 'link') continue;
                if (part.target.startsWith('#'))
                    expect(anchors.has(part.target.slice(1)), `${id}: ${part.target}`).toBe(true);
                else expect(['/security', '/status'], `${id}: ${part.target}`).toContain(part.target);
            }
        }
        // The intro strip's risk links land on the page's risk sections.
        for (const a of ['short-risks', 'lend-risks', 'lender-limits', 'borrower-limits'])
            expect(anchors.has(a), a).toBe(true);
        // And those sections hold the approved texts the strip names (verbatim there).
        const at = (anchor: string) => HOW_IT_WORKS.findIndex((b) => 'anchor' in b && b.anchor === anchor);
        const next = (from: number) => HOW_IT_WORKS.slice(from + 1).find((b) => b.kind === 'disclosure');
        expect(next(at('short-risks'))).toMatchObject({ disclosure: 'borrower.liquidation', open: true });
        expect(next(at('lend-risks'))).toMatchObject({ disclosure: 'lender.risks', open: true });
    });

    it('names the coverage notice in both links (WCAG 2.5.3: the visible text is the name)', () => {
        expect(copy('coverage.link.inline')).toContain('coverage notice');
        expect(copy('coverage.link.sheet')).toContain('coverage notice');
        expect(copy('coverage.link.sheet')).not.toContain('above');
        expect(copy('intro.dismiss.aria')).toContain(copy('intro.dismiss'));
    });

    it('is in FRONTEND.md §4.3 word for word, as the owner approved it on 2026-10-11', () => {
        const doc = readRepo('docs/design/FRONTEND.md');
        const s43 = doc.slice(doc.indexOf('### 4.3'), doc.indexOf('## 5.'));
        expect(s43).not.toContain('pending owner approval');
        expect(s43).toContain('approved as written by the owner on 2026-10-11 (thirteenth');
        for (const id of ids) {
            // Each string under its own id, exactly as `owner-copy.ts --doc` writes it.
            expect(s43, id).toContain(`- \`${id}\` (${COPY[id].where}):\n  > ${COPY[id].text}\n`);
        }
    });

    it('carries the mobile-wallet strings as the owner approved them as drafted on 2026-10-13', () => {
        expect(MOBILE_APPROVAL).toBe('approved as drafted by the owner on 2026-10-13 (O-6 lifted)');
        const doc = readRepo('docs/design/FRONTEND.md');
        const s43 = doc.slice(doc.indexOf('### 4.3'), doc.indexOf('## 5.'));
        const group = s43.indexOf(`**Mobile wallets** (\`src/config/copyWallet.ts\`; O-6, ${MOBILE_APPROVAL}):`);
        expect(group).toBeGreaterThan(0);
        // Byte for byte as drafted (straight apostrophes, no final full stops; mobile.md §3).
        const drafted: Record<keyof typeof WALLET_COPY, string> = {
            'wallet.openIn.more': 'Or open this page in a wallet app',
            'wallet.webview.open': 'Open this page in your browser',
            'wallet.webview.copy': 'Copy link',
            'wallet.mwa.label': 'Use installed wallet',
            'wallet.mwa.hint': 'Opens your wallet app on this phone',
            'wallet.mwa.localNetwork': "Allow 'Apps on device' so this page can reach your wallet app",
            'wallet.mwa.retry': "Couldn't open your wallet app. Tap Sign again",
        };
        expect(Object.keys(WALLET_COPY)).toEqual(Object.keys(drafted));
        for (const [id, text] of Object.entries(drafted) as [keyof typeof WALLET_COPY, string][]) {
            expect(WALLET_COPY[id].text, id).toBe(text);
            expect(COPY[id].text, id).toBe(text);
            expect(walletCopy(id), id).toBe(text);
            // Listed under the mobile group's approval line.
            expect(s43.indexOf(`- \`${id}\` (`), id).toBeGreaterThan(group);
        }
    });

    it('carries pump’s v3 error texts as the program returns them and the owner approved them as drafted (D4)', () => {
        expect(PUMP_APPROVAL).toBe('approved as drafted by the owner on 2026-10-13 (pump-final D4)');
        const doc = readRepo('docs/design/FRONTEND.md');
        const s43 = doc.slice(doc.indexOf('### 4.3'), doc.indexOf('## 5.'));
        const group = s43.indexOf(
            `**pump’s v3 adapter: the program’s error texts** (\`src/config/copyPump.ts\`; ${PUMP_APPROVAL}):`,
        );
        expect(group).toBeGreaterThan(0);
        // Byte for byte as drafted in pump-final §17 D4 (a straight apostrophe; no final full stop
        // on CurveStraddle), and as the program's `#[msg]` returns them.
        const drafted: Record<keyof typeof PUMP_COPY, readonly [number, string, string]> = {
            'error.curveCashbackCoin': [
                6109,
                'CurveCashbackCoin',
                "pump.fun's current trades do not support cashback coins on the curve. This coin can be shorted once it graduates to PumpSwap.",
            ],
            'error.curveStraddle': [
                6031,
                'CurveStraddle',
                'Buyback exceeds what the curve and its post-migration pool can deliver',
            ],
        };
        const rs = readRepo('programs/shortwin/src/errors.rs');
        const msg = (variant: string) =>
            new RegExp(`#\\[msg\\(\\s*"((?:[^"\\\\]|\\\\.)*)"\\s*\\)\\]\\s*${variant},`).exec(rs)?.[1];
        expect(Object.keys(PUMP_COPY)).toEqual(Object.keys(drafted));
        for (const [id, [code, name, text]] of Object.entries(drafted) as [
            keyof typeof PUMP_COPY,
            readonly [number, string, string],
        ][]) {
            expect(PUMP_COPY[id].text, id).toBe(text);
            expect(COPY[id].text, id).toBe(text);
            expect(msg(name), name).toBe(text);
            expect(programError(code)?.name, id).toBe(name);
            expect(programError(code)?.message, id).toBe(text);
            // Listed under the pump group's approval line.
            expect(s43.indexOf(`- \`${id}\` (`), id).toBeGreaterThan(group);
        }
    });

    it('pins the approved set: all 152 strings, and §4.3’s catalogue is the generated one exactly', () => {
        // Intro strip 13, How it works 42, links 3, O-2 2, O-5 3, mobile wallets 7, pump's v3
        // error texts 2; the glossary control 2 and its 78 entries (glossary.test.ts checks those
        // one by one, the quoted paragraphs included).
        expect(ids).toHaveLength(72);
        expect(ids.length + Object.keys(GLOSSARY_UI).length + Object.keys(GLOSSARY).length).toBe(152);
        const doc = readRepo('docs/design/FRONTEND.md');
        const block = doc.slice(doc.indexOf(BEGIN), doc.indexOf(END) + END.length);
        expect(block).toBe(docBlock());
    });
});
