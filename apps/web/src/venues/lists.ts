export type { ExtrasChoice, ExtrasSelection } from './types.ts';

export const NO_EXTRAS: ExtrasChoice = {
    sel: { set: EXTRAS_SET.none, bumps: new Uint8Array(4) },
    metas: [],
    label: 'none',
};

/** The extras seed of a venue (`VenueKind::extras_seed`), `null` for a venue without venue CPIs. */
export function extrasSeed(kind: KindName): number | null {
    switch (kind) {
        case 'pump_curve':
            return 1;
        case 'pump_swap':
            return 3;
        case 'raydium_v4':
            return 4;
        case 'raydium_cpmm':
            return 5;
        case 'mock':
            return 6;
        default:
            return null;
    }
}

/** The market's pool for a template's `pool` placeholder (`venues::pool_key`). */
function poolKey(kind: KindName, m: MarketKeys): Address | null {
    switch (kind) {
        case 'mock':
        case 'raydium_v4':
        case 'raydium_cpmm':
            return cached(m, RAY_CACHE.pool);
        case 'pump_swap':
            return m.canonicalPool;
        default:
            return null;
    }
}

function placeholderKey(id: number, kind: KindName, m: MarketKeys): Address | null {
    switch (id) {
        case PLACEHOLDER.mint:
            return m.mint;
        case PLACEHOLDER.pool:
            return poolKey(kind, m);
        case PLACEHOLDER.trader:
            return m.trader;
        case PLACEHOLDER.bondingCurve:
            return m.bondingCurve;
        case PLACEHOLDER.coinCreator:
            // The program resolves it on PumpSwap to the cached coin creator (`venues::parse`).
            return kind === 'pump_swap' ? cached(m, PAMM_CACHE.cachedCoinCreator) : null;
        default:
            return null;
    }
}

async function resolveEntry(e: ExtraEntry, kind: KindName, m: MarketKeys): Promise<readonly [Address, number] | null> {
    if (e.kind === ENTRY.fixed) return [e.key, 0];
    if (e.kind !== ENTRY.template) return null;
    const n = e.nSeeds;
    if (n === 0 || n > EXTRAS_MAX_SEEDS) return null;
    const seeds: Uint8Array[] = [];
    for (const part of e.seeds.slice(0, n)) {
        if (part.kind === SEED.const) {
            if (part.len > 32) return null;
            seeds.push(new Uint8Array(part.bytes).slice(0, part.len));
        } else if (part.kind === SEED.placeholder) {
            const k = placeholderKey(part.len, kind, m);
            if (!k) return null;
            seeds.push(new Uint8Array(getAddressEncoder().encode(k)));
        } else return null;
    }
    const [key, bump] = await findPda(e.key, seeds);
    return [key, bump];
}

async function choiceOf(
    set: ExtrasSet,
    which: number,
    label: ExtrasChoice['label'],
    extrasKey: Address,
    kind: KindName,
    m: MarketKeys,
): Promise<ExtrasChoice | null> {
    const n = set.count;
    if (n === 0) return null;
    const metas: AccountMeta[] = [meta(extrasKey, false)];
    const bumps = new Uint8Array(4);
    for (let i = 0; i < n; i++) {
        const e = set.entries[i];
        if (!e) return null;
        const r = await resolveEntry(e, kind, m);
        if (!r) return null;
        if (i < 4) bumps[i] = r[1];
        metas.push(meta(r[0], e.writable === 1));
    }
    return { sel: { set: which, bumps }, metas, label };
}

/**
 * The extras sets to try for instruction kind `ix` (`EXTRAS_IX_*`), in the keeper's order:
 * `current`, `none`, `previous`, `stable` (`venue::extras_candidates`); a set with no entries is
 * only ever `none`, and a set whose template cannot be resolved is left out.
 */
export async function extrasCandidates(
    kind: KindName,
    ix: number,
    m: MarketKeys,
    extras: VenueExtras | null,
): Promise<ExtrasChoice[]> {
    const seed = extrasSeed(kind);
    if (!extras || seed === null) return [NO_EXTRAS];
    const ixe = extras.sets[ix];
    if (!ixe) return [NO_EXTRAS];
    const key = await venueExtrasPda(seed);
    const out: ExtrasChoice[] = [];
    const current = await choiceOf(ixe.current, EXTRAS_SET.current, 'current', key, kind, m);
    if (current) out.push(current);
    out.push(NO_EXTRAS);
    const previous = await choiceOf(ixe.previous, EXTRAS_SET.previous, 'previous', key, kind, m);
    if (previous) out.push(previous);
    const stable = await choiceOf(ixe.stable, EXTRAS_SET.stable, 'stable', key, kind, m);
    if (stable) out.push(stable);
    return out;
}
