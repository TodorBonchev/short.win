/**
 * Per-venue account lists (ARCH §3.0 "Remaining-accounts convention", §3.12): a TypeScript port of
 * `services/keeper/src/venue.rs` — the ReadSet, its writability in trades, the TradeExtras (with
 * the slots the program checks against live state read from this read's ReadSet accounts), the
 * extras sets of A41 with their placeholders resolved, and the PumpSwap coin-creator vault
 * preparation (M6-SEC-4). The slot order and writability are the program's
 * (`programs/shortwin/src/venues/*`); `lists.test.ts` holds every list to the keeper's own output
 * (`vectors/keeper-vectors.json`, generated by `vectors/keeper_vectors.rs`).
 *
 * One deliberate difference from the keeper: a pump recipient is chosen **at random** from the
 * live list (FRONTEND.md §5.1 — users' trades should not all write-lock one recipient), where the
 * keeper spreads its own exits by the mint's first byte. Both are entries the program accepts
 * (C0-14). `recipientIndex` makes the choice injectable for tests.
 */
