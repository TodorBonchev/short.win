/** ReadSet slots (ARCH §3.12). */
export const CURVE_SLOT = {
    curve: 0,
    global: 1,
    feeConfig: 2,
    canonicalPool: 3,
    curveBaseAta: 4,
    pammFeeConfig: 5,
    pammGlobalConfig: 6,
} as const;
export const PAMM_SLOT = {
    pool: 0,
    baseVault: 1,
    quoteVault: 2,
    globalConfig: 3,
    feeConfig: 4,
    boostVaultAta: 5,
    lpMint: 6,
} as const;
export const V4_SLOT = { pool: 0, coinVault: 1, pcVault: 2, lpMint: 3 } as const;
export const CPMM_SLOT = { pool: 0, ammConfig: 1, token0Vault: 2, token1Vault: 3, lpMint: 4 } as const;
export const MOCK_SLOT = { pool: 0, baseVault: 1, quoteVault: 2 } as const;

const meta = (address: Address, writable: boolean): AccountMeta => ({
    address,
    role: writable ? AccountRole.WRITABLE : AccountRole.READONLY,
});

export function cached(market: MarketKeys, i: number): Address {
    return (market.poolCache[i] as Address | undefined) ?? DEFAULT_KEY;
}

/** Raydium: WSOL is the AMM v4 coin / the CPMM token 0 (`Market.flags` bit 3). */
export function solFirst(market: MarketKeys): boolean {
    return (market.flags & MARKET_FLAG.solIsToken0OrCoin) !== 0;
}

/** Which ReadSet slots are writable in a trade (`read_writable`). */
export function readWritable(kind: KindName): readonly boolean[] {
    switch (kind) {
        case 'raydium_v4':
            return [true, true, true, false];
        case 'raydium_cpmm':
            return [true, false, true, true, false];
        case 'pump_curve':
        case 'pump_migrating':
            return [true, false, false, false, true, false, false];
        case 'pump_swap':
            return [true, true, true, false, false, false, false];
        case 'mock':
            return [true, true, true];
        case 'none':
            return [false, false];
    }
}

/** The ReadSet keys of a market on `kind` (`read_set`; PumpSwap's P6 derived as `create_pool` does). */
export async function readSet(kind: KindName, m: MarketKeys): Promise<Address[]> {
    const sol = cached(m, RAY_CACHE.vaultSol);
    const tok = cached(m, RAY_CACHE.vaultTok);
    const [first, second] = solFirst(m) ? [sol, tok] : [tok, sol];
    switch (kind) {
        case 'raydium_v4':
            return [cached(m, RAY_CACHE.pool), first, second, cached(m, RAY_CACHE.lpMint)];
        case 'raydium_cpmm':
            return [
                cached(m, RAY_CACHE.pool),
                cached(m, RAY_CACHE.ammConfig),
                first,
                second,
                cached(m, RAY_CACHE.lpMint),
            ];
        case 'pump_curve':
        case 'pump_migrating':
            return [
                m.bondingCurve,
                PUMP_GLOBAL,
                PUMP_FEE_CONFIG,
                m.canonicalPool,
                m.curveBaseAta,
                PUMP_AMM_FEE_CONFIG,
                PUMP_AMM_GLOBAL_CONFIG,
            ];
        case 'pump_swap':
            return [
                m.canonicalPool,
                cached(m, PAMM_CACHE.poolBaseVault),
                cached(m, PAMM_CACHE.poolQuoteVault),
                PUMP_AMM_GLOBAL_CONFIG,
                PUMP_AMM_FEE_CONFIG,
                cached(m, PAMM_CACHE.boostVaultAta),
                await pammLpMint(m.canonicalPool),
            ];
        case 'mock':
            return [cached(m, RAY_CACHE.pool), tok, sol];
        case 'none':
            return [m.bondingCurve, m.canonicalPool];
    }
}

/** The ReadSet metas (`read_metas`): writable per `readWritable` when `trading`, read-only otherwise. */
export function readMetas(kind: KindName, keys: readonly Address[], trading: boolean): AccountMeta[] {
    const w = readWritable(kind);
    if (w.length !== keys.length)
        throw new Error(`venue ${kind}: ${keys.length} ReadSet keys, the adapter takes ${w.length}`);
    return keys.map((k, i) => meta(k, trading && (w[i] ?? false)));
}

/** Picks a recipient index of an 8-entry list (default: uniformly at random). */
export type RecipientIndex = (list: readonly Address[], market: MarketKeys) => number;

/** The keeper's choice: the mint's first byte (`venue::recipient`). */
export const keeperRecipientIndex: RecipientIndex = (list, market) =>
    (getAddressEncoder().encode(market.mint)[0] ?? 0) % Math.max(1, list.length);

export const randomRecipientIndex: RecipientIndex = (list) => {
    const b = new Uint8Array(1);
    crypto.getRandomValues(b);
    return (b[0] ?? 0) % Math.max(1, list.length);
};

/** The first non-default entry of a live recipient list from `start` on (`venue::recipient`). */
export function recipient(list: readonly Address[], start: number): Address {
    const n = list.length;
    for (let k = 0; k < n; k++) {
        const r = list[(start + k) % n];
        if (r && r !== DEFAULT_KEY) return r;
    }
    throw new Error('the live list names no recipient');
}

/** The ReadSet account at `slot`, or `null`. */
function at(read: readonly (RawAccount | null)[], slot: number): RawAccount | null {
    return read[slot] ?? null;
}

/** A PumpSwap pool's coin-creator vault authority (T12) and its WSOL ATA (T11): the cache's, else derived. */
export async function pammCreatorAccounts(m: MarketKeys, coinCreator: Address): Promise<readonly [Address, Address]> {
    if (
        coinCreator === cached(m, PAMM_CACHE.cachedCoinCreator) &&
        cached(m, PAMM_CACHE.cachedCoinCreatorVaultAuth) !== DEFAULT_KEY
    ) {
        return [cached(m, PAMM_CACHE.cachedCoinCreatorVaultAuth), cached(m, PAMM_CACHE.cachedCoinCreatorVaultAta)];
    }
    const a = await pammCoinCreatorVaultAuthority(coinCreator);
    return [a, await wsolAta(a)];
}

/** The trader's pAMM UVA (T14): the cache, else derived (`venue::uva_of`). */
export async function pammUvaOf(m: MarketKeys): Promise<Address> {
    const c = cached(m, PAMM_CACHE.uva);
    return c === DEFAULT_KEY ? pammUserVolumeAccumulator(m.trader) : c;
}

/** The TradeExtras metas of a market on `kind` (`trade_extras`); `read` is this read's ReadSet accounts. */
export async function tradeExtras(
    kind: KindName,
    m: MarketKeys,
    read: readonly (RawAccount | null)[],
    pick: RecipientIndex = randomRecipientIndex,
): Promise<AccountMeta[]> {
    switch (kind) {
        case 'raydium_v4':
            return [
                meta(RAYDIUM_V4_PROGRAM, false),
                meta(RAYDIUM_V4_AUTHORITY, false),
                meta(TOKEN_PROGRAM, false),
                meta(WSOL_MINT, false),
                meta(SYSTEM_PROGRAM, false),
                meta(m.traderWsol, true),
            ];
        case 'raydium_cpmm':
            return [
                meta(RAYDIUM_CPMM_PROGRAM, false),
                meta(RAYDIUM_CPMM_AUTHORITY, false),
                meta(cached(m, RAY_CACHE.observation), true),
                meta(TOKEN_PROGRAM, false),
                meta(m.tokenProgram, false),
                meta(WSOL_MINT, false),
                meta(SYSTEM_PROGRAM, false),
                meta(m.traderWsol, true),
            ];
        case 'mock':
            return [
                meta(MOCK_CPAMM_PROGRAM, false),
                meta(MOCK_CPAMM_AUTHORITY, false),
                meta(WSOL_MINT, false),
                meta(TOKEN_PROGRAM, false),
                meta(m.traderWsol, true),
            ];
        case 'pump_curve':
            return pumpTradeExtras(m, read, pick);
        case 'pump_swap':
            return pammTradeExtras(m, read, pick);
        case 'pump_migrating':
            throw new VenueError('VenueMigrating', 'a migrating curve has no trade');
        case 'none':
            throw new VenueError('NoRoute', 'a list-only market has no trade');
    }
}

/** A venue that cannot trade, with the program error the trade would fail with. */
export class VenueError extends Error {
    readonly code: string;
    constructor(code: string, message: string) {
        super(message);
        this.code = code;
        this.name = 'VenueError';
    }
}

async function pumpTradeExtras(
    m: MarketKeys,
    read: readonly (RawAccount | null)[],
    pick: RecipientIndex,
): Promise<AccountMeta[]> {
    const g = at(read, CURVE_SLOT.global);
    const c = at(read, CURVE_SLOT.curve);
    const global = g ? value(readPumpGlobal(g.owner, g.data)) : null;
    const curve = c ? value(readCurve(c.owner, c.data)) : null;
    if (!global) throw new VenueError('NoRoute', 'pump Global not read');
    if (!curve) throw new VenueError('NoRoute', 'bonding curve not read');
    const fee = recipient(global.feeRecipients, pick(global.feeRecipients, m));
    const buyback = recipient(global.buybackFeeRecipients, pick(global.buybackFeeRecipients, m));
    const vault = curve.creator === m.cachedCreator ? m.cachedCreatorVault : await pumpCreatorVault(curve.creator);
    const [feeAta, buybackAta, traderWsolAta, vaultAta] = await Promise.all([
        wsolAta(fee),
        wsolAta(buyback),
        wsolAta(m.trader),
        wsolAta(vault),
    ]);
    return [
        meta(PUMP_PROGRAM, false),
        meta(PUMP_EVENT_AUTHORITY, false),
        meta(PUMP_FEES_PROGRAM, false),
        meta(WSOL_MINT, false),
        meta(TOKEN_PROGRAM, false),
        meta(ASSOCIATED_TOKEN_PROGRAM, false),
        meta(fee, true),
        meta(feeAta, true),
        meta(buyback, true),
        meta(buybackAta, true),
        meta(m.curveQuoteAta, true),
        meta(traderWsolAta, true),
        meta(vault, true),
        meta(vaultAta, true),
        meta(m.sharingConfig, false),
        meta(PUMP_GLOBAL_VOLUME_ACCUMULATOR, false),
        meta(m.pumpUva, true),
        meta(m.pumpUvaQuoteAta, true),
        meta(m.traderBaseAta, true),
        meta(SYSTEM_PROGRAM, false),
    ];
}

async function pammTradeExtras(
    m: MarketKeys,
    read: readonly (RawAccount | null)[],
    pick: RecipientIndex,
): Promise<AccountMeta[]> {
    const p = at(read, PAMM_SLOT.pool);
    const pool = p ? value(readPammPool(p.owner, p.data)) : null;
    if (!pool) throw new VenueError('NoRoute', 'PumpSwap pool not read');
    const gc = at(read, PAMM_SLOT.globalConfig);
    const g = gc ? value(readPammGlobalConfig(gc.owner, gc.data)) : null;
    if (!g) throw new VenueError('NoRoute', 'PumpSwap GlobalConfig not read');
    const protocol = recipient(g.protocolFeeRecipients, pick(g.protocolFeeRecipients, m));
    const buyback = recipient(g.buybackFeeRecipients, pick(g.buybackFeeRecipients, m));
    const [auth, authAta] = await pammCreatorAccounts(m, pool.coinCreator);
    const uva = await pammUvaOf(m);
    const markerCached = cached(m, PAMM_CACHE.poolV2Marker);
    const marker = markerCached === DEFAULT_KEY ? await pammPoolV2(m.mint) : markerCached;
    const cashbackCached = cached(m, PAMM_CACHE.uvaQuoteAta);
    const cashback = cashbackCached === DEFAULT_KEY ? await wsolAta(uva) : cashbackCached;
    const [protocolAta, buybackAta] = await Promise.all([wsolAta(protocol), wsolAta(buyback)]);
    return [
        meta(PUMP_AMM_PROGRAM, false),
        meta(PUMP_AMM_EVENT_AUTHORITY, false),
        meta(PUMP_FEES_PROGRAM, false),
        meta(WSOL_MINT, false),
        meta(TOKEN_PROGRAM, false),
        meta(ASSOCIATED_TOKEN_PROGRAM, false),
        meta(SYSTEM_PROGRAM, false),
        meta(m.traderBaseAta, true),
        meta(m.traderWsol, true),
        meta(protocol, false),
        meta(protocolAta, true),
        meta(authAta, true),
        meta(auth, false),
        meta(PUMP_AMM_GLOBAL_VOLUME_ACCUMULATOR, false),
        meta(uva, true),
        meta(marker, false),
        meta(buyback, false),
        meta(buybackAta, true),
        meta(cashback, true),
    ];
}

/**
 * M6-SEC-4 (`venue::pamm_creator_vault_prep`): on a PumpSwap market whose live pool names another
 * coin creator than the cache, `create_idempotent(ATA(creator vault authority, WSOL))` paid by
 * `payer`, so the trade's existence requirement holds. `null` otherwise.
 */
export async function pammCreatorVaultPrep(
    payer: TransactionSigner,
    m: MarketKeys,
    kind: KindName,
    read: readonly (RawAccount | null)[],
): Promise<Instruction | null> {
    if (kind !== 'pump_swap') return null;
    const p = at(read, PAMM_SLOT.pool);
    const pool = p ? value(readPammPool(p.owner, p.data)) : null;
    if (!pool || pool.coinCreator === cached(m, PAMM_CACHE.cachedCoinCreator)) return null;
    const [auth, ataKey] = await pammCreatorAccounts(m, pool.coinCreator);
    return getCreateAssociatedTokenIdempotentInstruction({
        payer,
        ata: ataKey,
        owner: auth,
        mint: WSOL_MINT,
        tokenProgram: TOKEN_PROGRAM,
    });
}

