function groupsOf(): { title: string; ids: GlossaryId[] }[] {
    const ids = Object.keys(GLOSSARY) as GlossaryId[];
    return GLOSSARY_GROUPS.map(([title, first], i) => {
        const from = ids.indexOf(first);
        const next = GLOSSARY_GROUPS[i + 1];
        const to = next ? ids.indexOf(next[1]) : ids.length;
        return { title, ids: ids.slice(from, to) };
    });
}

const quoteRef = (e: GlossaryEntry) =>
    e.quote ? `D:${e.quote.disclosure} ${e.quote.paragraphs.map((p) => `¶${p + 1}`).join(', ')}` : '';

/** An entry's text as shipped: its own, or the quoted approved paragraphs (verbatim, unfilled). */
function entryText(e: GlossaryEntry): string {
    if (!e.quote) return e.text ?? '';
    const body = DISCLOSURES[e.quote.disclosure].body;
    return e.quote.paragraphs.map((p) => body[p] ?? '').join(' ');
}

