/** The How it works page in its order: page-level strings, then the blocks. */
function pageIds(): CopyId[] {
    const out: CopyId[] = ['howItWorks.title', 'howItWorks.lead', 'howItWorks.toc.aria', 'howItWorks.configError'];
    for (const b of HOW_IT_WORKS) {
        if (b.kind === 'list') out.push(...b.ids);
        else if (b.kind !== 'disclosure') out.push(b.id);
    }
    out.push('howItWorks.back');
    return out;
}

function row(id: string, text: string, where: string, sources: string): string {
    const cell = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');
    return `| \`${id}\` | ${cell(where)} | ${cell(text)} | ${cell(sources)} |`;
}

const HEAD = '| id | Where it shows | Text (exactly as shipped) | Sources |\n|---|---|---|---|';

function copyTable(list: readonly CopyId[]): string {
    return [HEAD, ...list.map((id) => row(id, COPY[id].text, COPY[id].where, COPY[id].sources))].join('\n');
}

