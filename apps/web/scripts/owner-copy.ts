/** FRONTEND.md §4.3's catalogue: every string verbatim with its id (no sources: see the owner file). */
export function docBlock(): string {
    const out: string[] = [BEGIN, ''];
    const para = (id: string, where: string, text: string) => out.push(`- \`${id}\` (${where}):`, `  > ${text}`);
    out.push('**Intro strip, How it works, links, O-2, O-5** (`src/config/copy.ts`):', '');
    for (const id of Object.keys(COPY) as CopyId[]) para(id, COPY[id].where, COPY[id].text);
    out.push('', '**The glossary control** (`src/config/glossary.ts` `GLOSSARY_UI`):', '');
    for (const [id, text] of Object.entries(GLOSSARY_UI)) para(id, 'the ⓘ', text);
    out.push('', '**Glossary entries** (`src/config/glossary.ts`; *beside*: the labels it attaches to):', '');
    for (const id of Object.keys(GLOSSARY) as GlossaryId[]) {
        const e: GlossaryEntry = GLOSSARY[id];
        const beside = e.labels.length ? e.labels.map((l) => `“${l}”`).join(', ') : 'its status bar item';
        // A quote entry's text, printed under its reference: a disclosure paragraph added, dropped or
        // moved changes what the entry shows, and so §4.3 (copy.test compares the block).
        if (e.quote)
            out.push(
                `- \`glossary.${id}\` — ${e.term}; beside ${beside}: *verbatim, ${quoteRef(e)}*`,
                `  > ${entryText(e)}`,
            );
        else para(`glossary.${id}`, `${e.term}; beside ${beside}`, entryText(e));
    }
    out.push('', END);
    return out.join('\n');
}

/** Run as a script (not imported by the tests). */
const isMain = !!process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
    const arg = process.argv[2];
    if (arg === '--doc') {
        const doc = readFileSync(FRONTEND, 'utf8');
        const a = doc.indexOf(BEGIN);
        const b = doc.indexOf(END);
        if (a < 0 || b < a) throw new Error('FRONTEND.md: the copy markers are missing (§4.3)');
        writeFileSync(FRONTEND, doc.slice(0, a) + docBlock() + doc.slice(b + END.length));
        console.log('FRONTEND.md §4.3 updated');
    } else if (arg) {
        writeFileSync(arg, ownerCopy());
        console.log(`wrote ${arg}`);
    } else {
        process.stdout.write(ownerCopy());
    }
}
